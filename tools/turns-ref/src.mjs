// The real turns of each circuit layout, as people who know the circuit number and name them (official circuit maps, the
// series' own maps, Wikipedia's track pages). One entry per layout:
//   key    the circuit and layout
//   ids    the game's own track ids with this layout ("game:id"); the first one is the layout the turns are placed on
//   match  words of the circuit's name, for a game that has no id here yet (with the lap's length they choose the layout)
//   seq    T1 … Tn in order: "R" or "L" (which way it turns), "*2" two turns in one bend (a double apex), "@1234" the
//          metres from the line on the first layout when the bend is too light to be found alone, "X" a numbered turn
//          with no bend at all (placed between its neighbours, or at its @), then its name ("A/B" the names of a *2)
//   sure   false when the numbering could not be checked against a map with the turns' numbers (SOURCES below says
//          which map each list was checked against)
// node tools/turns-ref/build.mjs writes cloud/src/turnsref-data.js from this and the layouts of the server.
